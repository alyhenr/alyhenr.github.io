#!/usr/bin/env node
/**
 * Bundles Studio's traco-wireframe (vendor/studio/traco-wireframe, as delivered) with the parts of
 * three it uses into the one ES module the home's stage loads: js/scene/traco-wireframe.js.
 *
 *   node tools/bundle-scene.mjs           writes the bundle
 *   node tools/bundle-scene.mjs --check   fails when the committed bundle isn't what this makes
 *
 * The site has no build step: this runs by hand when a new version of the package (or of three)
 * is taken, and its output is committed. three and esbuild are pinned dev dependencies
 * (package.json), so the bundle is reproducible, and the QA's `scene` step checks it is current
 * and within the scene's download budget (BUDGET, gzip).
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const ENTRY = 'vendor/studio/traco-wireframe/index.js';
export const OUT = 'js/scene/traco-wireframe.js';
/** design/scenes/traco-wireframe.md: ≤ 140 KB gzip of script (KiB, as Studio measures it). */
export const BUDGET = 140 * 1024;

/** The bundle's bytes, built in memory. */
export async function build(root = ROOT) {
  const { build: esbuild } = await import('esbuild');
  const pkg = (p) => JSON.parse(readFileSync(join(root, p), 'utf8')).version;
  const banner = `/* traco-wireframe ${pkg('vendor/studio/traco-wireframe/package.json')} (Studio) with three ${pkg('node_modules/three/package.json')} (MIT, threejs.org). Generated by tools/bundle-scene.mjs: never edit. */`;
  const r = await esbuild({
    absWorkingDir: root,
    entryPoints: [ENTRY],
    bundle: true,
    format: 'esm',
    minify: true,
    target: 'es2020',
    legalComments: 'none',
    banner: { js: banner },
    write: false,
    logLevel: 'silent',
  });
  return Buffer.from(r.outputFiles[0].contents);
}

export const gzipSize = (buf) => gzipSync(buf, { level: 9 }).length;

/** What's wrong with the committed bundle (stale, missing, over budget), or undefined. */
export async function check(root = ROOT) {
  const out = [];
  const file = join(root, OUT);
  const fresh = await build(root);
  if (!existsSync(file)) out.push(`${OUT} is missing: run node tools/bundle-scene.mjs`);
  else if (!readFileSync(file).equals(fresh)) out.push(`${OUT} is not what tools/bundle-scene.mjs makes from ${ENTRY}: rebundle it`);
  const size = gzipSize(fresh);
  if (size > BUDGET) out.push(`the scene's script is ${(size / 1024).toFixed(1)} KB gzip, over its ${BUDGET / 1024} KB budget`);
  return out.length ? out.join('\n') : undefined;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const bad = await check();
    if (bad) { console.error(bad); process.exit(1); }
    console.log(`${OUT} is current`);
  } else {
    const buf = await build();
    mkdirSync(dirname(join(ROOT, OUT)), { recursive: true });
    writeFileSync(join(ROOT, OUT), buf);
    console.log(`${OUT}: ${(buf.length / 1024).toFixed(1)} KB, ${(gzipSize(buf) / 1024).toFixed(1)} KB gzip (budget ${BUDGET / 1024})`);
  }
}
